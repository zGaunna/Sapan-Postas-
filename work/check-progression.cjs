const assert = require('node:assert/strict');
const { game, context, element, dispatchKeyUp } = require('./check-game.cjs');
const log = context.VoyageLog;
assert.equal(log.list().length,0,'Automated normal routes must be excluded');
context.__playtestRun = false;
game.resetRun(-1); game.update(.1); game.finishRun(true);
assert.equal(log.list().length,1);
assert.equal(log.list()[0].won,true);
assert.equal(log.list()[0].time,game.runTime());
assert.equal(log.list()[0].seals,0);
game.finishRun(true);
assert.equal(log.list().length,1,'A finished run is logged exactly once');
game.toggleLog(); assert.equal(game.state(),'history');
assert.match(element('#log-rows').innerHTML,/Fenere vardın/);
game.toggleLog(); assert.equal(game.state(),'won');
game.resetRun(0); game.update(.1); game.finishRun(true);
game.startSealPractice(2); game.startRecovery(); game.finishRun(true);
assert.equal(log.list().length,1,'Both training modes must stay out of the log');
game.resetRun(-1); game.update(.2); game.finishRun(false,'timeout');
assert.equal(log.list().length,2);
assert.equal(log.list()[0].reason,'timeout');
context.__playtestRun = true;
game.resetRun(-1); game.finishRun(true);
assert.equal(log.list().length,2,'Explicit test runs must stay out of the log');

game.resetRun(0);
Object.assign(game.player,{x:440,y:400,vx:200,vy:0}); game.beginTether();
const ring = game.tetherAnchor(), throws=game.stats().cleanThrows;
game.toggleMap();
assert.equal(game.travelToDock('invalid'),false);
assert.equal(game.state(),'map','Invalid travel must preserve the map');
dispatchKeyUp('Space');
assert.equal(ring.visited,false,'Releasing a held key in the map must not consume the ring');
assert.equal(game.stats().cleanThrows,throws);
game.toggleMap();
game.toggleLog();
const frozen = JSON.stringify({player:game.player,rig:game.courier.snapshot(),time:game.runTime(),visual:game.visualTime()});
for(let i=1;i<30;i++) game.frame(10000+i*16);
assert.equal(JSON.stringify({player:game.player,rig:game.courier.snapshot(),time:game.runTime(),visual:game.visualTime()}),frozen);
game.toggleLog(); assert.equal(game.state(),'playing');
game.enterHarbor('vinc'); game.player.x=5720; game.openConversation();
const dialog = game.conversation(); game.toggleLog(); game.toggleLog();
assert.equal(game.state(),'exploring'); assert.equal(game.conversation(),dialog);
element('#sound-toggle').click();
assert.equal(context.localStorage.getItem('sapan-postasi-sound'),'on');
element('#motion-toggle').click();
assert.equal(context.localStorage.getItem('sapan-postasi-motion'),'reduced');
console.log('Progression checks passed: normal-only history integration, single recording, overlays freeze, safe held-key release, invalid travel, preserved conversation and saved preferences.');
