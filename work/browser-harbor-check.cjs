const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(process.argv[2] || "playwright");
(async () => {
  const output = path.join(__dirname, "evidence"); fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
  const page = await context.newPage(); const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const url = process.env.GAME_URL || "http://127.0.0.1:8765";
  await page.goto(url);
  await page.locator("#explore-button").click();
  assert.equal(await page.locator("#social-hud").isVisible(), true);
  await page.keyboard.down("d"); await page.waitForTimeout(650); await page.keyboard.up("d");
  await page.keyboard.press("e");
  assert.equal(await page.locator("#dialogue").isVisible(), true);
  assert.equal(await page.locator("#dialogue-name").textContent(), "Emine abla");
  assert.match(await page.locator("#dialogue-text").textContent(), /Gel kardeşim/);
  await page.keyboard.press("1");
  assert.match(await page.locator("#dialogue-text").textContent(), /Yusuf abine/);
  await page.screenshot({ path: path.join(output, "rihtim-conversation.png") });
  await page.keyboard.press("Escape");
  await page.keyboard.press("m");
  assert.equal(await page.locator("#harbor-map").isVisible(), true);
  await page.screenshot({ path: path.join(output, "harbor-map.png") });
  await page.locator('[data-dock="vinc"]').click();
  assert.equal(await page.locator("#social-place").textContent(), "Vinç Avlusu");
  await page.screenshot({ path: path.join(output, "vinc-dock.png") });
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("#pause-screen").isVisible(), true);
  const canvasBefore = await page.locator("#game").evaluate(c => c.toDataURL());
  await page.waitForTimeout(150);
  assert.equal(await page.locator("#game").evaluate(c => c.toDataURL()), canvasBefore);
  await page.locator("#resume-button").click();
  await page.keyboard.press("m");
  await page.locator('[data-dock="dalgakiran"]').click();
  await page.screenshot({ path: path.join(output, "dalgakiran-dock.png") });
  await page.keyboard.press("m");
  await page.locator('[data-dock="fener"]').click();
  await page.screenshot({ path: path.join(output, "fener-dock.png") });
  await page.locator("#harbor-leave-button").click();
  assert.equal(await page.locator("#start-screen").isVisible(), true);

  await page.goto(url + "/work/browser-playtest.html");
  const result = await page.evaluate(() => {
    const g = __playtest;
    g.resetRun(0); g.update(0.1);
    const before = JSON.stringify({ player: g.player, time: g.runTime() });
    g.enterHarbor("rihtim"); g.keys.add("KeyD");
    for (let i = 0; i < 180; i++) g.updateSocial(1/120);
    const walking = { x: g.player.x, state: g.state(), time: g.runTime() };
    g.keys.clear(); g.player.x = 310; g.openConversation();
    const name = g.conversation().person.name;
    g.chooseConversation(0); g.closeConversation(); g.travelToDock("fener");
    g.leaveHarbor();
    return { before, after: JSON.stringify({ player: g.player, time: g.runTime() }), walking, name };
  });
  assert.equal(result.before, result.after, "Visiting all docks must not alter the suspended route");
  assert.equal(result.walking.state, "exploring"); assert.equal(result.name, "Emine abla");
  for (const [name, x] of [["rihtim", 1000], ["pazar", 4400], ["vinc", 8600], ["dalgakiran", 13600], ["fener", 16800]]) {
    await page.evaluate(x => { const g = __playtest; g.resetRun(0); g.player.x = x; g.player.y = 410;
      g.player.vx = 0; g.player.vy = 0; g.update(0); g.draw(10); }, x);
    await page.screenshot({ path: path.join(output, `district-${name}.png`) });
  }
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ errors, walking: result.walking, routeRestored: true, screenshots: output }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
